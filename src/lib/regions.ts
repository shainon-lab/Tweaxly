export function isRegionCode(s: unknown): s is string {
  return typeof s === "string" && REGIONS.some((r) => r.code === s);
}

export function regionName(code: string | null | undefined): string | null {
  if (!code) return null;
  return REGIONS.find((r) => r.code === code)?.name ?? null;
}
